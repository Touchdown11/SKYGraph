function metrics=extractMultiEgoMetricsStage16(output)
%EXTRACTMULTIEGOMETRICSSTAGE16 One-row and per-ego metrics for Stage 16.
N=size(output.Position,2); perEgoSuccess=output.FinalGoalError(:)<.25;
metrics=table(N,output.Configuration.Scenario,string(output.Configuration.PolicyMode), ...
    output.MissionSuccess,any(output.Collision),min(output.MinimumPairwiseSeparation), ...
    mean(output.CBFIntervention,'all'),mean(output.GraphNodes,'all'),mean(output.GraphEdges,'all'), ...
    mean(output.FinalGoalError),mean(perEgoSuccess), ...
    'VariableNames',{'NumberOfEgos','Scenario','PolicyMode','MissionSuccess','AnyCollision', ...
    'MinimumPairwiseSeparation','CBFInterventionRate','MeanGraphNodes','MeanGraphEdges', ...
    'MeanFinalGoalError','PerEgoSuccessRate'});
end
